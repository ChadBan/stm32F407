void lcd_show_char(uint16_t x, uint16_t y, char ch, uint16_t color, uint16_t bg)
{
    if (ch >= 'a' && ch <= 'z')
        ch = (char)(ch - 'a' + 'A'); /* 小写降级为大写 */
    uint8_t idx = (ch < 0x20 || ch > 0x5F) ? 0u : (uint8_t)(ch - 0x20);
    const uint8_t *p = FONT8x16[idx];

    if (x + 8 > LCD_WIDTH || y + 16 > LCD_HEIGHT)
        return;
    lcd_set_window(x, y, (uint16_t)(x + 7), (uint16_t)(y + 15));
    for (int row = 0; row < 16; row++)
    {
        uint8_t bits = p[row];
        for (int col = 0; col < 8; col++)
        {
            lcd_write_data16((bits & 0x80) ? color : bg);
            bits <<= 1;
        }
    }
}

void lcd_show_string(uint16_t x, uint16_t y, const char *s, uint16_t color, uint16_t bg)
{
    if (s == NULL)
        return;
    while (*s)
    {
        lcd_show_char(x, y, *s++, color, bg);
        x += LCD_CHAR_W;
    }
}
