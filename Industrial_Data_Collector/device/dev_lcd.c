/**
 * @file    dev_lcd.c
 * @brief   ILI9488 3.5寸 TFT LCD（FSMC 8080 16bit 并口）驱动实现
 *
 * FSMC Bank1 region4（NE4=PD7）映射到 0x6C000000；16bit 数据宽度下
 * HADDR[25:1] -> FSMC_A[24:0]，故 RS(A6) = HADDR[7] = 0x80。
 * 写 0x6C000000（A6=0）= 命令，写 0x6C000080（A6=1）= 数据/GRAM。
 */
#include "dev_lcd.h"
#include "stm32f4xx.h"

/* ============ FSMC 内存映射 ============ */
#define LCD_REG (*(volatile uint16_t *)0x6C000000UL)          /* RS=0 命令 */
#define LCD_RAM (*(volatile uint16_t *)(0x6C000000UL | 0x80UL)) /* RS=1 数据 */

static void lcd_write_cmd(uint8_t cmd) { LCD_REG = cmd; }
static void lcd_write_data(uint8_t d) { LCD_RAM = d; }
static void lcd_write_data16(uint16_t d) { LCD_RAM = d; }

/* 设置 GRAM 窗口（ILI9488 横屏 480x320：列 0-479，页 0-319） */
static void lcd_set_window(uint16_t x0, uint16_t y0, uint16_t x1, uint16_t y1)
{
    lcd_write_cmd(0x2A); /* Column Address Set */
    lcd_write_data((uint8_t)(x0 >> 8));
    lcd_write_data((uint8_t)(x0 & 0xFF));
    lcd_write_data((uint8_t)(x1 >> 8));
    lcd_write_data((uint8_t)(x1 & 0xFF));
    lcd_write_cmd(0x2B); /* Page Address Set */
    lcd_write_data((uint8_t)(y0 >> 8));
    lcd_write_data((uint8_t)(y0 & 0xFF));
    lcd_write_data((uint8_t)(y1 >> 8));
    lcd_write_data((uint8_t)(y1 & 0xFF));
    lcd_write_cmd(0x2C); /* Memory Write */
}

static void lcd_reset(void)
{
    LCD_RST_LOW();
    HAL_Delay(50);
    LCD_RST_HIGH();
    HAL_Delay(50);
}

void lcd_init(void)
{
    lcd_reset();

    /* 正极性 gamma（PGAMCTRL） */
    lcd_write_cmd(0xE0);
    lcd_write_data(0x00); lcd_write_data(0x03); lcd_write_data(0x09);
    lcd_write_data(0x08); lcd_write_data(0x16); lcd_write_data(0x0A);
    lcd_write_data(0x3F); lcd_write_data(0x78); lcd_write_data(0x4C);
    lcd_write_data(0x09); lcd_write_data(0x0A); lcd_write_data(0x08);
    lcd_write_data(0x16); lcd_write_data(0x1A); lcd_write_data(0x0F);

    /* 负极性 gamma（NGAMCTRL） */
    lcd_write_cmd(0xE1);
    lcd_write_data(0x00); lcd_write_data(0x1B); lcd_write_data(0x1F);
    lcd_write_data(0x07); lcd_write_data(0x0F); lcd_write_data(0x03);
    lcd_write_data(0x34); lcd_write_data(0x41); lcd_write_data(0x4A);
    lcd_write_data(0x0B); lcd_write_data(0x13); lcd_write_data(0x0B);
    lcd_write_data(0x23); lcd_write_data(0x3E); lcd_write_data(0x1A);

    lcd_write_cmd(0xC0); lcd_write_data(0x19); /* VREG1OUT */
    lcd_write_cmd(0xC1); lcd_write_data(0x10); /* VREG2OUT */
    lcd_write_cmd(0xC5);                        /* VCOM control */
    lcd_write_data(0x00); lcd_write_data(0x22); lcd_write_data(0x80);
    lcd_write_cmd(0xB0); lcd_write_data(0x00);  /* interface mode control */
    lcd_write_cmd(0xB1); lcd_write_data(0xB0);  /* frame rate control */
    lcd_write_cmd(0xB4); lcd_write_data(0x02);  /* display inversion control */
    lcd_write_cmd(0xB6);                        /* display function control */
    lcd_write_data(0x02); lcd_write_data(0x02); lcd_write_data(0x3B);
    lcd_write_cmd(0x3A); lcd_write_data(0x55);  /* 16bit RGB565 */
    lcd_write_cmd(0x36); lcd_write_data(0x28);  /* MADCTL：横屏 + BGR */

    lcd_write_cmd(0x11); /* Sleep out */
    HAL_Delay(120);
    lcd_write_cmd(0x29); /* Display on */

    lcd_clear(COLOR_BLACK);
    LCD_BL_ON();
}

void lcd_clear(uint16_t color)
{
    lcd_fill(0, 0, LCD_WIDTH - 1, LCD_HEIGHT - 1, color);
}

void lcd_fill(uint16_t x0, uint16_t y0, uint16_t x1, uint16_t y1, uint16_t color)
{
    if (x0 > x1 || y0 > y1 || x1 >= LCD_WIDTH || y1 >= LCD_HEIGHT)
        return;
    lcd_set_window(x0, y0, x1, y1);
    uint32_t n = (uint32_t)(x1 - x0 + 1) * (uint32_t)(y1 - y0 + 1);
    while (n--)
        lcd_write_data16(color);
}

void lcd_draw_point(uint16_t x, uint16_t y, uint16_t color)
{
    if (x >= LCD_WIDTH || y >= LCD_HEIGHT)
        return;
    lcd_set_window(x, y, x, y);
    lcd_write_data16(color);
}

